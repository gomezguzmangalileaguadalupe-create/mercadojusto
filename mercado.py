def optimizar_ganancias_reactivo(producto, costo_fijo, costo_variable, ganancia_deseada):
    df_filtrado = df[df['producto'] == producto].sort_values('fecha')
    precio_actual = df_filtrado.iloc[-1]['precio_kg'] if not df_filtrado.empty else 250

    if precio_actual <= costo_variable:
        return "<div style='background-color:#FFEBEE; padding:20px; border-radius:8px; border-left: 8px solid #D32F2F;'><h4 style='color:#C62828; margin:0;'>⚠️ Alerta Crítica: Costo variable supera el precio de mercado. Operación inviable.</h4></div>", go.Figure()

    # Cálculos Financieros Estructurales
    margen = precio_actual - costo_variable
    pto_equilibrio = costo_fijo / margen
    meta_kilos = (costo_fijo + ganancia_deseada) / margen

    resumen = f"""
    <div style='display:flex; justify-content:space-around; background-color:#F5F5F5; padding: 15px; border-radius: 10px; border: 1px solid #E0E0E0; gap: 10px; margin-top: 15px;'>
        <div style='text-align:center; flex:1;'>
            <p style='margin:0; font-size:12px; font-weight:700; color:#666666; text-transform:uppercase;'>Precio Mercado</p>
            <span style='font-size:1.8em; font-weight:800; color:#0288D1;'>${precio_actual:.2f}</span>
        </div>
        <div style='text-align:center; flex:1; border-left: 1px solid #DCDCDC; border-right: 1px solid #DCDCDC;'>
            <p style='margin:0; font-size:12px; font-weight:700; color:#666666; text-transform:uppercase;'>Punto Equilibrio</p>
            <span style='font-size:1.8em; font-weight:800; color:#F57C00;'>{pto_equilibrio:.0f} kg</span>
        </div>
        <div style='text-align:center; flex:1;'>
            <p style='margin:0; font-size:12px; font-weight:700; color:#666666; text-transform:uppercase;'>Meta de Venta</p>
            <span style='font-size:1.8em; font-weight:800; color:#388E3C;'>{meta_kilos:.0f} kg</span>
        </div>
    </div>
    """

    # Rango de volumen para el gráfico dinámico
    max_kg = int(meta_kilos * 1.6) if meta_kilos > 0 else 500
    kg_rango = np.linspace(0, max_kg, 100)
    ingresos = kg_rango * precio_actual
    costos = costo_fijo + (kg_rango * costo_variable)

    fig_opt = go.Figure()

    # 1. ZONA DE PÉRDIDA (Sombreado Rojo Seguro antes del Punto de Equilibrio)
    kg_perdida = np.linspace(0, pto_equilibrio, 50)
    ingresos_p = kg_perdida * precio_actual
    costos_p = costo_fijo + (kg_perdida * costo_variable)
    fig_opt.add_trace(go.Scatter(
        x=np.concatenate([kg_perdida, kg_perdida[::-1]]),
        y=np.concatenate([ingresos_p, costos_p[::-1]]),
        fill='toself',
        fillcolor='rgba(244, 67, 54, 0.15)',
        line=dict(color='rgba(255,255,255,0)'),
        hoverinfo='skip',
        name='Área de Pérdida'
    ))

    # 2. ZONA DE GANANCIA (Sombreado Verde Seguro después del Punto de Equilibrio)
    kg_ganancia = np.linspace(pto_equilibrio, max_kg, 50)
    ingresos_g = kg_ganancia * precio_actual
    costos_g = costo_fijo + (kg_ganancia * costo_variable)
    fig_opt.add_trace(go.Scatter(
        x=np.concatenate([kg_ganancia, kg_ganancia[::-1]]),
        y=np.concatenate([ingresos_g, costos_g[::-1]]),
        fill='toself',
        fillcolor='rgba(76, 175, 80, 0.20)',
        line=dict(color='rgba(255,255,255,0)'),
        hoverinfo='skip',
        name='Área de Ganancia'
    ))

    # 3. LÍNEAS DE TENDENCIA FINANCIERA PRINCIPALES
    fig_opt.add_trace(go.Scatter(x=kg_rango, y=costos, name='Costos Totales (Fijos + Variables)', line=dict(color='#D32F2F', width=3)))
    fig_opt.add_trace(go.Scatter(x=kg_rango, y=ingresos, name='Ingresos Brutos', line=dict(color='#2E7D32', width=3)))

    # 4. INDICADOR VERTICAL EXPLICATIVO: PUNTO DE EQUILIBRIO
    fig_opt.add_vline(x=pto_equilibrio, line_dash="dash", line_color="#E65100", line_width=2)
    fig_opt.add_trace(go.Scatter(
        x=[pto_equilibrio],
        y=[pto_equilibrio * precio_actual],
        mode='markers+text',
        name='Punto de Equilibrio',
        text=[f" Equilibrio ({pto_equilibrio:.0f} kg)"],
        textposition="top left",
        marker=dict(color='#E65100', size=10, symbol='circle')
    ))

    # Configuración de diseño y etiquetas claras
    fig_opt.update_layout(
        title=f'Análisis de Umbral Financiero para Corte {producto.capitalize()}',
        xaxis_title='Volumen Vendido / Producido (Kilogramos)',
        yaxis_title='Flujo de Capital (MXN)',
        template='plotly_white',
        hovermode="x unified",
        margin=dict(l=40, r=40, t=50, b=40),
        legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1)
    )

    return resumen, fig_opt


def optimizar_logistica_mapa(producto, costo_base_produccion, costo_diesel_km):
    try:
        mejor_estado = ""
        mejor_margen = -999999

        G = nx.Graph()
        for u, v, dist in conexiones_logísticas:
            costo_viaje = dist * costo_diesel_km
            G.add_edge(u, v, weight=costo_viaje, distancia=dist)

        arbol_minimo = nx.minimum_spanning_tree(G, algorithm="kruskal")

        for est, coords in coordenadas_estados.items():
            df_est = df[(df['producto'] == producto) & (df['estado'] == est)].sort_values('fecha')
            precio_mkt = df_est.iloc[-1]['precio_kg'] if not df_est.empty else 230

            costo_transporte = (coords['distancia_hub'] * costo_diesel_km) / 500
            margen_neto = precio_mkt - (costo_base_produccion + costo_transporte)

            if margen_neto > mejor_margen:
                mejor_margen = margen_neto
                mejor_estado = est

        mapa_folium = folium.Map(location=[23.6345, -102.5528], zoom_start=5, tiles="OpenStreetMap")

        for estado, coords in coordenadas_estados.items():
            df_est = df[(df['producto'] == producto) & (df['estado'] == estado)]
            precio_actual = df_est.iloc[-1]['precio_kg'] if not df_est.empty else 230

            info_popup = f"""
            <div style='font-family: Arial, sans-serif; min-width: 160px;'>
                <b style='color:#1A237E;'>{estado}</b><br>
                <b>Precio Actual:</b> ${precio_actual:.2f} MXN/kg<br>
                <b>Distancia Hub:</b> {coords['distancia_hub']} km
            </div>
            """
            pin_color = "purple" if estado == mejor_estado else "red"

            folium.Marker(
                location=[coords['lat'], coords['lon']],
                popup=folium.Popup(info_popup, max_width=250),
                tooltip=f"Haga clic para ver {estado}",
                icon=folium.Icon(color=pin_color, icon="truck", prefix="fa")
            ).add_to(mapa_folium)

        costo_total_red = 0
        for u, v, data in arbol_minimo.edges(data=True):
            costo_tramo = data['weight']
            dist_tramo = data['distancia']
            costo_total_red += costo_tramo

            coord_u = [coordenadas_estados[u]['lat'], coordenadas_estados[u]['lon']]
            coord_v = [coordenadas_estados[v]['lat'], coordenadas_estados[v]['lon']]

            folium.PolyLine(
                locations=[coord_u, coord_v],
                color="#1B5E20",
                weight=5,
                opacity=0.85,
                tooltip=f"Enlace Óptimo Kruskal: {u} ↔ {v} ({dist_tramo} km)"
            ).add_to(mapa_folium)

        mapa_html = mapa_folium._repr_html_()

        kpi_mapa = f"""
        <div style='background-color: #F3E5F5; padding: 20px; border-radius: 10px; text-align: center; border: 1px solid #CE93D8; border-left: 8px solid #8E24AA; box-shadow: 0 4px 6px rgba(0,0,0,0.05); margin-top: 15px;'>
            <p style='margin: 0; font-size: 13px; font-weight: 700; color: #4A148C; text-transform: uppercase; letter-spacing: 1px;'>Estrategia del Algoritmo Kruskal</p>
            <h1 style='margin: 8px 0; font-size: 2.2em; color: #6A1B9A; font-weight: 800;'>{mejor_estado}</h1>
            <p style='margin: 0; font-size: 12px; font-weight: 600; color: #2A085C;'>Margen Neto Comercial Estimado: ${mejor_margen:.2f} MXN/kg</p>
            <div style='margin-top:10px; font-size:11px; background-color:rgba(255,255,255,0.5); padding:4px; border-radius:4px;'>
                <b>Costo total de distribución de la red:</b> ${costo_total_red:,.2f} MXN
            </div>
        </div>
        """
        return kpi_mapa, mapa_html

    except Exception as e:
        return f"<h3 style='color:red; text-align:center;'>⚠️ Error en el mapeo logístico: {str(e)}</h3>", ""

